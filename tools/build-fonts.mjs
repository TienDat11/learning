// tools/build-fonts.mjs — regenerate assets/fonts.css (Genesis faces) as base64 woff2 data URIs.
// Run once when fonts change: `node tools/build-fonts.mjs`. build.mjs only reads assets/fonts.css.
// Sources: Be Vietnam Pro (display + body) and JetBrains Mono (code), both Google Fonts with
// latin/latin-ext/vietnamese subsets. Be Vietnam Pro is primary because it covers all
// U+1EA0–1EF9 diacritics (measured 102/102 via CDP CSS.getPlatformFontsForNode); General Sans
// (missing 64/102) and DM Sans (missing 90/102, no vietnamese subset) were deleted.
// Weights are limited to 400 and 600 by design.
import { readFileSync, writeFileSync, existsSync, mkdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const dir = join(root, 'assets', 'fonts');
mkdirSync(dir, { recursive: true });
const UA = 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/120.0 Safari/537.36';
const KEEP = new Set(['latin', 'latin-ext', 'vietnamese']);

const GOOGLE = [
  { family: 'JetBrains Mono', q: 'JetBrains+Mono:wght@400;600', tag: 'jbmono' },
  { family: 'Be Vietnam Pro', q: 'Be+Vietnam+Pro:wght@400;600', tag: 'bvnpro' },
];

const faces = [];

for (const g of GOOGLE) {
  const css = await (await fetch(`https://fonts.googleapis.com/css2?family=${g.q}&display=swap`, { headers: { 'User-Agent': UA } })).text();
  const re = /\/\*\s*([\w-]+)\s*\*\/\s*@font-face\s*\{([^}]*)\}/g;
  let m;
  while ((m = re.exec(css))) {
    const [, subset, body] = m;
    if (!KEEP.has(subset)) continue;
    const weight = Number(/font-weight:\s*(\d+)/.exec(body)[1]);
    const url = /url\((https:[^)]+)\)/.exec(body)[1];
    const range = /unicode-range:\s*([^;]+);/.exec(body)[1];
    const data = Buffer.from(await (await fetch(url)).arrayBuffer());
    faces.push({ family: g.family, weight, data, subset, range, tag: g.tag });
  }
}

const blocks = faces.map((f) => {
  const b64 = f.data.toString('base64');
  const range = f.range ? `\n  unicode-range:${f.range};` : '';
  const label = f.subset ? `/* ${f.family} ${f.weight} ${f.subset} */\n` : `/* ${f.family} ${f.weight} (full set in file) */\n`;
  return `${label}@font-face{font-family:"${f.family}";font-style:normal;font-weight:${f.weight};font-display:swap;${range}\n  src:url(data:font/woff2;base64,${b64}) format("woff2");}`;
});

const header = `/* assets/fonts.css — Genesis type system, self-hosted (generated by tools/build-fonts.mjs).
   Be Vietnam Pro (display + body), JetBrains Mono (code). Weights 400 + 600 only.
   build.mjs inlines this into the single-file build. No network at runtime. */\n\n`;
writeFileSync(join(root, 'assets', 'fonts.css'), header + blocks.join('\n\n') + '\n', 'utf8');
console.log(`wrote assets/fonts.css with ${faces.length} faces`);
